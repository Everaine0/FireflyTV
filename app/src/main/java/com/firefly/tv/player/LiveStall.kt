package com.firefly.tv.player

/**
 * 直播「画面不动了」的判据。
 *
 * 抽成纯函数，是因为这条判据的触发时机（断流那一刻）靠手点很难复现，而**判错的代价不对称**：
 * 漏判只是维持现状（画面冻着），误判却会把**正在正常播放**的画面打断重来 ——
 * 所以边界必须能用单测钉死。
 *
 * ## 主判据：播放器自报「一直在缓冲」
 *
 * `MEDIA_INFO_BUFFERING_START` 是**播放器自己**报的，实测丢包后 **0 毫秒**就到，
 * 而画面也正是那一刻冻住的。它的 Java 回调确实会送达（探针实测：丢包后第一轮巡检就看到
 * `缓冲=5813ms`），所以「持续缓冲超过 [BUFFERING_MS]」就是目前最可信的断流判据。
 *
 * ⚠️ 两个**不能**用作判据的量（都是实测否掉的，换设备也别再试）：
 *
 *  1. **送显帧率**（`videoOutputFramesPerSecond`）：它是「每出一帧才更新一次」的速率量，
 *     管线停住以后**不归零，而是停在最后一个值上**。实测画面冻住 3 分钟，它一直是 25.00；
 *     而在 SMB + `IMediaDataSource` 通路上它又**恒为 0**。两头都会骗人，只能当辅助判据。
 *  2. **流量字节数**（`trafficStatisticByteCount`）：本以为是「累计计数器，收不到数据就不涨」，
 *     实测在 RTSP 通路上**恒为 0**（探针实测：正常播放 25 帧/秒时也是 `流量=0B`）——
 *     和上面那个量在 SMB 上的坏法一样。拿它当判据的版本写出来了却一次都没触发，
 *     正是这一条把看门狗憋死的。（顺带：诊断页那行「读 x MB/秒」就是由它算的，
 *     所以直播时永远显示 0.0，别拿它判断网络。）
 *
 * 另外两件实测知道的事，决定了判据的形状：
 *
 *  - `MEDIA_INFO_BUFFERING_END` 在断流后**不会来**（网络恢复也不来），所以缓冲时刻**不能**
 *    等它来清 —— 由看门狗在判定重连时清掉（见 `IjkPlaybackEngine` 的 `bufferingSince`）。
 *  - 起播瞬间也可能报缓冲。这类「首帧之前的缓冲」必须作废，否则一路正常的直播会在
 *    开播十几秒后被自己的看门狗判死 —— 所以 `fireFirstFrame()` 里会把缓冲时刻清零。
 */
internal object LiveStall {

    /** 判定「画面真的在动」的送显帧率门槛（帧/秒）。直播片源最低也有 23.976 帧/秒。 */
    const val MIN_FPS = 0.5f

    /**
     * 播放器自报缓冲持续超过这么久，就认定这一路已经断了。
     *
     * 取 10 秒：正常的抖动、换台前后的空档都远短于它（实测正常播放时这个值一直是 0），
     * 而老人对着冻住的画面也不该等更久。
     */
    const val BUFFERING_MS = 10_000L

    /**
     * 巡检周期（引擎每隔这么久问一次判据）。
     *
     * 放在这里和门槛一起，是因为**用户等待的时间 ≈ 门槛 + 周期 × 次数**，
     * 这三个数必须一起看：[WORST_CASE_MS] 把它们钉成一个可断言的契约。
     */
    const val RECHECK_MS = 5_000L

    /**
     * 连续几次判定卡死才真的重连。
     *
     * 取 3：留一点迟滞，不因为一次抖动就打断画面；又不能让老人对着冻住的画面干等。
     * 25 秒（界面层的起播超时）那种量级太久了。
     */
    const val MAX_STRIKES = 3

    /**
     * 从「断流发生」到「发起重连」的最坏耗时（毫秒）。
     *
     * 实测意义：用户看到画面冻住之后，最多这么久就会自动重连（重连本身还有 2 秒起的退避）。
     * 单测直接断言这个上界，避免以后调门槛时把等待时间悄悄拉到半分钟。
     */
    const val WORST_CASE_MS = BUFFERING_MS + RECHECK_MS * MAX_STRIKES

    /**
     * 这一轮巡检要不要记一笔「卡死」。
     *
     * @param playing 播放器自认为在播（用户按暂停时为 false）
     * @param outputFps 送显帧率；⚠️ 管线停住后它会停在最后一个值上，不能单独作数
     * @param bufferingMs 播放器自报「正在缓冲」已经持续了多久（0 = 没在缓冲）
     */
    fun strike(
        playing: Boolean,
        outputFps: Float,
        bufferingMs: Long,
    ): Boolean {
        // 主判据：播放器一直在等数据，等了 10 秒还没等到 —— 这就是断流
        val streamStarved = bufferingMs >= BUFFERING_MS
        // 辅助判据：播放器说自己在播，却一帧都送不出去（真机上「解码器卡住」是这种）。
        // 这条在某些通路上永远不会成立（见类注释），留着是为了那些通路之外的设备。
        val framesStuck = playing && outputFps <= MIN_FPS
        return streamStarved || framesStuck
    }
}
